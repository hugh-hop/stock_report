  get(name, size, color) {
    size = size || 24;
    let def = this.defs[name];
    if (!def) return '';
    let key = name + '_' + size + '_' + (color || '');
    if (this._cache[key]) return this._cache[key];
    let rects = this._renderPixels(def.pixels, def.palette);
    let svg = '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 16 16" shape-rendering="crispEdges" role="img" aria-label="' + def.aria + '">' + rects + '</svg>';
    this._cache[key] = svg;
    return svg;
  },

  _renderPixels(pixels, palette) {
    let rows = pixels.split('|');
    let rects = '';
    for (let y = 0; y < rows.length && y < 16; y++) {
      let row = rows[y];
      for (let x = 0; x < row.length && x < 16; x++) {
        let ch = row[x];
        if (ch !== '.' && palette[ch]) {
          rects += '<rect x="' + x + '" y="' + y + '" width="1" height="1" fill="' + palette[ch] + '"/>';
        }
      }
    }
    return rects;
  },

  getDataUri(name, color) {
    let def = this.defs[name];
    if (!def) return '';
    let rects = this._renderPixels(def.pixels, def.palette);
    let svg = '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" shape-rendering="crispEdges">' + rects + '</svg>';
    return 'data:image/svg+xml,' + encodeURIComponent(svg);
  },

  createImage(name, size, color) {
    size = size || 24;
    let def = this.defs[name];
    if (!def) return new Image();
    let rects = this._renderPixels(def.pixels, def.palette);
    let svg = '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 16 16" shape-rendering="crispEdges">' + rects + '</svg>';
    let blob = new Blob([svg], { type: 'image/svg+xml' });
    let url = URL.createObjectURL(blob);
    let img = new Image();
    img.src = url;
    img.onload = () => URL.revokeObjectURL(url);
    return img;
  },

  preload(size, color) {
    size = size || 24;
    let images = {};
    for (let name of Object.keys(this.defs)) {
      images[name] = this.createImage(name, size, color);
    }
    return images;
  },

  replaceInText(text, size, color) {
    return text.replace(/\[icon:(\w+)\]/g, (match, name) => {
      return this.get(name, size, color);
    });
  },

